"""Cuts frame-sequence rows out of the uploaded FX sheet into even strips for js/fx.js.

Each row's frames sit at uneven spacing with small number labels under them, so every frame is
found as a connected blob in the row's band, labels dropped, then centred in an equal square cell.
Writes assets/art/fx/<name>.png (one row of cells) and js/fxstrips.js (frame counts and sizes).

    python3 tools/build_fx_strips.py
"""
import json
import os

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHEET = os.path.join(ROOT, 'assets/art/source/uploads/fx-explosions-weapons-shields.png')
OUT = os.path.join(ROOT, 'assets/art/fx')
CELL = 96

# name: (x0, y0, x1, y1) of the row's frames on the sheet (labels underneath are filtered out).
# The bands stop just above the number labels and below the row titles.
ROWS = {
    'explosion': (815, 189, 1536, 271),
    'magic-blue': (372, 318, 748, 403),
    'magic-purple': (752, 318, 1122, 403),
    'magic-green': (1132, 318, 1500, 403),
    'shield-up': (60, 809, 778, 881),
    'shield-break': (780, 809, 1536, 881),
}


def frames(sheet, box):
    x0, y0, x1, y1 = box
    crop = sheet.crop(box)
    a = np.array(crop)[..., 3]
    lab, _ = ndimage.label(ndimage.binary_dilation(a > 24, iterations=1))
    blobs = []
    for i, o in enumerate(ndimage.find_objects(lab)):
        h, w = o[0].stop - o[0].start, o[1].stop - o[1].start
        # Number labels: short boxes sitting at the bottom of the band.
        if h < 22 or (o[0].start > (y1 - y0) - 26 and h < 30):
            continue
        blobs.append([o[1].start, o[0].start, o[1].stop, o[0].stop])
    blobs.sort()
    # Join blobs that overlap sideways (one frame broken into puffs).
    merged = []
    for b in blobs:
        if merged and b[0] < merged[-1][2] - 4:
            m = merged[-1]
            merged[-1] = [min(m[0], b[0]), min(m[1], b[1]), max(m[2], b[2]), max(m[3], b[3])]
        else:
            merged.append(b)
    # A blob much wider than it is tall is several touching frames: split it evenly.
    split = []
    for bx0, by0, bx1, by1 in merged:
        n = max(1, round((bx1 - bx0) / max(1, by1 - by0)))
        step = (bx1 - bx0) / n
        split += [[round(bx0 + k * step), by0, round(bx0 + (k + 1) * step), by1] for k in range(n)]
    # One cell size for the whole row, so frames keep their sizes relative to each other.
    side = max(max(b[2] - b[0], b[3] - b[1]) for b in split)
    out = []
    for bx0, by0, bx1, by1 in split:
        f = crop.crop((bx0, by0, bx1, by1))
        cell = Image.new('RGBA', (side, side), (0, 0, 0, 0))
        cell.paste(f, ((side - f.width) // 2, (side - f.height) // 2))
        out.append(cell.resize((CELL, CELL), Image.LANCZOS))
    return out


def main():
    sheet = Image.open(SHEET).convert('RGBA')
    os.makedirs(OUT, exist_ok=True)
    meta = {}
    for name, box in ROWS.items():
        fr = frames(sheet, box)
        strip = Image.new('RGBA', (CELL * len(fr), CELL), (0, 0, 0, 0))
        for i, f in enumerate(fr):
            strip.paste(f, (i * CELL, 0))
        strip.save(os.path.join(OUT, f'{name}.png'), optimize=True)
        meta[name] = {'frames': len(fr), 'cell': CELL}
        print(name, len(fr))
    with open(os.path.join(ROOT, 'js/fxstrips.js'), 'w') as fh:
        fh.write('// Generated by tools/build_fx_strips.py: frame strips cut from the uploaded FX sheet.\n')
        fh.write(f'window.CardshipsFxStrips = {json.dumps(meta)};\n')


if __name__ == '__main__':
    main()
